namespace Amarin.Core;

/// <summary>Сколько живёт разговор чата с агентом (1.37.0): до какого момента ему можно написать.</summary>
/// <remarks>
/// Значения только дописываются в конец: в <c>settings.json</c> перечисление пишется именем, и
/// переименованное значение прежняя запись уже не прочла бы.
/// </remarks>
public enum AgentMemory
{
    /// <summary>До конца ответа, в котором агента запустили, — как было до 1.37.0.</summary>
    Answer,

    /// <summary>Пока программа открыта: чат пишет агенту любого прошлого ответа.</summary>
    Session,

    /// <summary>Сохраняется в файле чата и переживает перезапуск.</summary>
    Chat
}
