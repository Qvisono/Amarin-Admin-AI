namespace Amarin.Core;

/// <summary>
/// Обрезка длинного текста для служебных запросов.
/// </summary>
/// <remarks>
/// Отдельный класс, потому что обрезают в двух местах — маршрутизатор чата и маршрутизатор уровня
/// агента, — и оба по одной причине: до неё вставка на десятки килобайт целиком оплачивалась
/// служебным запросом ещё до того, как начиналась настоящая работа.
/// </remarks>
internal static class TextClip
{
    /// <summary>Сколько символов запроса показывать служебной модели с начала и с конца.</summary>
    /// <remarks>
    /// Маршрутизатор и выбор продолжения решают по сути запроса, а не по его объёму: полторы
    /// тысячи символов начала и полтысячи конца её передают, а дальше растёт только цена.
    /// </remarks>
    public const int DecisionHead = 1500;

    /// <inheritdoc cref="DecisionHead"/>
    public const int DecisionTail = 500;

    /// <summary>Сколько показывать от предыдущего запроса: он только уточняет нынешний.</summary>
    public const int ContextHead = 300;

    /// <param name="tail">
    /// Сколько символов сохранить с конца. У длинного текста заключительный вопрос обычно
    /// именно там, поэтому ноль ставят только там, где хвост заведомо не нужен.
    /// </param>
    public static string Clip(string text, int head, int tail)
    {
        if (text.Length <= head + tail)
        {
            return text;
        }

        return tail > 0
            ? text[..head] + " […] " + text[^tail..]
            : text[..head] + " […]";
    }
}
