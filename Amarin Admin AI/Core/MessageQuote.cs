namespace Amarin.Core;

/// <summary>
/// Фрагмент прежнего ответа модели, на который человек отвечает своим сообщением.
/// </summary>
/// <remarks>
/// <para>
/// Лежит на сообщении человека (<see cref="ChatDisplayMessage.Quotes"/>), а не вписан в его
/// <see cref="ChatDisplayMessage.Text"/>: текст читают маршрутизатор «Авто», генератор заголовка
/// и сводки, правка сообщения — и всем им слова ассистента, выданные за слова человека, только
/// мешали бы. Модель получает цитаты отдельным блоком, который собирает
/// <see cref="ChatQuotes.Wrap"/>.
/// </para>
/// <para>
/// Номера порядкового у ответа-источника здесь нет намеренно: «ответ №3» разошёлся бы с тем,
/// что видит модель (отменённые ответы в историю не попадают, раунды инструментов добавляют
/// свои записи), а удаление хода сдвинуло бы весь счёт. Источник называется в момент сборки
/// запроса по <see cref="SourceMessageId"/>.
/// </para>
/// </remarks>
public sealed class MessageQuote
{
    /// <summary>
    /// Номер, под которым цитату видит человек и модель: <c>@1</c>, <c>@2</c>… Не
    /// перенумеровывается при удалении соседки — иначе уже набранное «@2» стало бы указывать
    /// на другой фрагмент.
    /// </summary>
    public int Number { get; set; }

    /// <summary><see cref="ChatDisplayMessage.Id"/> ответа, из которого взят фрагмент.</summary>
    public string SourceMessageId { get; set; } = "";

    /// <summary>Сам фрагмент — уже приведённый <see cref="ChatQuotes.Normalize"/> и обрезанный.</summary>
    public string Text { get; set; } = "";

    /// <summary>
    /// Строка вокруг короткого фрагмента, если без неё непонятно, какое из вхождений имелось в
    /// виду. Пусто у длинных фрагментов — те однозначны сами по себе.
    /// </summary>
    public string? Context { get; set; }
}
