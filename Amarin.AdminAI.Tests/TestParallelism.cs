using Xunit;

// Коллекции xUnit идут параллельно, а почти всё, на что здесь смотрят тесты, — общее на процесс:
// язык интерфейса (Loc и словарь в ресурсах приложения), тема (ThemeManager), масштаб (UiScale),
// открытые попапы (PopupManager), белый список загрузок (DownloadValidator). Одного этого хватало,
// чтобы суд идущий параллельно LocalizationTests — он на пару миллисекунд переключает интерфейс
// на английский — ронял соседей в других коллекциях: «1.5 KB» вместо «1,5 КБ», «Auto» вместо
// «Авто», английский текст отказа вместо русского. Падало каждый второй-третий прогон и каждый
// раз в другом месте, так что списать это на свою правку было проще, чем найти.
//
// Внутри коллекции тесты и так идут по одному, поэтому терять здесь нечего, кроме секунд:
// вся разница — тридцать секунд против пятидесяти на полном прогоне.
[assembly: CollectionBehavior(DisableTestParallelization = true)]
